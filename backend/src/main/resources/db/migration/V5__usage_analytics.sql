-- Usage analytics: page views from the website and every login attempt.
-- Personal data (IP, user agent, identity) is kept for a limited time (app.analytics.retention-days).

CREATE TABLE page_views (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at           TIMESTAMP WITH TIME ZONE NOT NULL,
    visitor_id   VARCHAR(40)  NOT NULL,
    session_id   VARCHAR(40)  NOT NULL,
    customer_id  BIGINT,
    path         VARCHAR(300) NOT NULL,
    area         VARCHAR(10)  NOT NULL,   -- STORE | ADMIN | DEV
    sku          VARCHAR(50),
    referrer     VARCHAR(300),
    source       VARCHAR(60),
    ip           VARCHAR(64),
    user_agent   VARCHAR(400),
    device       VARCHAR(10),
    browser      VARCHAR(30),
    os           VARCHAR(30),
    timezone     VARCHAR(60),
    language     VARCHAR(20),
    screen_w     INT
);
CREATE INDEX idx_page_views_at ON page_views (at);
CREATE INDEX idx_page_views_sku ON page_views (sku);

CREATE TABLE login_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at           TIMESTAMP WITH TIME ZONE NOT NULL,
    customer_id  BIGINT,
    identity     VARCHAR(200) NOT NULL,
    method       VARCHAR(10)  NOT NULL,   -- EMAIL | PHONE
    success      BOOLEAN      NOT NULL,
    new_account  BOOLEAN      NOT NULL DEFAULT FALSE,
    reason       VARCHAR(200),
    ip           VARCHAR(64),
    user_agent   VARCHAR(400),
    device       VARCHAR(10),
    browser      VARCHAR(30),
    os           VARCHAR(30)
);
CREATE INDEX idx_login_events_at ON login_events (at);
