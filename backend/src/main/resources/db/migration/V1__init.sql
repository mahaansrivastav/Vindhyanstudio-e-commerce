-- Portable SQL: runs on Postgres (dev/prod) and H2 in Postgres mode (local).
-- JSON payloads are stored as VARCHAR text to stay portable.

CREATE TABLE customers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120),
    email       VARCHAR(200) UNIQUE,
    phone       VARCHAR(20)  UNIQUE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE otp_codes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identity    VARCHAR(200) NOT NULL,
    code_hash   VARCHAR(100) NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    attempts    INT NOT NULL DEFAULT 0,
    consumed    BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_otp_identity ON otp_codes (identity, created_at);

CREATE TABLE addresses (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  BIGINT NOT NULL REFERENCES customers (id),
    name         VARCHAR(120) NOT NULL,
    phone        VARCHAR(20)  NOT NULL,
    line1        VARCHAR(250) NOT NULL,
    line2        VARCHAR(250),
    city         VARCHAR(100) NOT NULL,
    state        VARCHAR(100) NOT NULL,
    pincode      VARCHAR(10)  NOT NULL,
    is_default   BOOLEAN NOT NULL DEFAULT FALSE,
    deleted      BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE categories (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(100) NOT NULL UNIQUE,
    slug               VARCHAR(100) NOT NULL UNIQUE,
    hsn_code           VARCHAR(20),
    gst_rate           NUMERIC(5, 2) NOT NULL DEFAULT 18,
    weight_g           INT NOT NULL DEFAULT 100,
    length_cm          NUMERIC(6, 1) NOT NULL DEFAULT 10,
    width_cm           NUMERIC(6, 1) NOT NULL DEFAULT 10,
    height_cm          NUMERIC(6, 1) NOT NULL DEFAULT 5,
    lead_time_days     INT NOT NULL DEFAULT 3,
    customisation_spec VARCHAR(500),
    colours            VARCHAR(500),
    sizes              VARCHAR(500),
    returnable         BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order         INT NOT NULL DEFAULT 0
);

CREATE TABLE products (
    sku            VARCHAR(50) PRIMARY KEY,
    category_id    BIGINT NOT NULL REFERENCES categories (id),
    name           VARCHAR(200) NOT NULL,
    slug           VARCHAR(220) NOT NULL UNIQUE,
    description    VARCHAR(4000),
    mrp            NUMERIC(12, 2) NOT NULL,
    selling_price  NUMERIC(12, 2) NOT NULL,
    offer_pct      INT NOT NULL DEFAULT 0,
    stock          INT NOT NULL DEFAULT 0,
    active         BOOLEAN NOT NULL DEFAULT TRUE,
    synced_at      TIMESTAMP WITH TIME ZONE
);

CREATE TABLE product_images (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         VARCHAR(50) NOT NULL REFERENCES products (sku),
    file_name   VARCHAR(200) NOT NULL,
    storage_key VARCHAR(500) NOT NULL,
    checksum    VARCHAR(80),
    sort_order  INT NOT NULL DEFAULT 0
);

CREATE TABLE sync_runs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at  TIMESTAMP WITH TIME ZONE,
    rows_ok      INT NOT NULL DEFAULT 0,
    rows_failed  INT NOT NULL DEFAULT 0,
    errors_json  VARCHAR(20000)
);

CREATE TABLE orders (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no          VARCHAR(30) UNIQUE,
    customer_id       BIGINT NOT NULL REFERENCES customers (id),
    address_json      VARCHAR(2000) NOT NULL,
    ship_pincode      VARCHAR(10) NOT NULL,
    subtotal          NUMERIC(12, 2) NOT NULL,
    shipping_fee      NUMERIC(12, 2) NOT NULL,
    discount          NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total             NUMERIC(12, 2) NOT NULL,
    payment_mode      VARCHAR(20) NOT NULL,
    status            VARCHAR(30) NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_orders_customer ON orders (customer_id);
CREATE INDEX idx_orders_status ON orders (status);

CREATE TABLE order_items (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           BIGINT NOT NULL REFERENCES orders (id),
    sku                VARCHAR(50) NOT NULL,
    name               VARCHAR(200) NOT NULL,
    unit_price         NUMERIC(12, 2) NOT NULL,
    mrp                NUMERIC(12, 2) NOT NULL,
    qty                INT NOT NULL,
    hsn_code           VARCHAR(20),
    gst_rate           NUMERIC(5, 2) NOT NULL,
    customisation_json VARCHAR(4000)
);

CREATE TABLE order_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT NOT NULL REFERENCES orders (id),
    status       VARCHAR(30) NOT NULL,
    note         VARCHAR(500),
    actor        VARCHAR(50) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE payments (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id             BIGINT NOT NULL REFERENCES orders (id),
    provider             VARCHAR(20) NOT NULL,
    provider_order_id    VARCHAR(100) NOT NULL,
    provider_payment_id  VARCHAR(100),
    amount               NUMERIC(12, 2) NOT NULL,
    status               VARCHAR(20) NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_payments_provider_order ON payments (provider_order_id);

CREATE TABLE shipments (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          BIGINT NOT NULL UNIQUE REFERENCES orders (id),
    provider          VARCHAR(20) NOT NULL,
    provider_order_id VARCHAR(100),
    shipment_id       VARCHAR(100),
    awb               VARCHAR(100),
    courier           VARCHAR(100),
    label_url         VARCHAR(500),
    tracking_url      VARCHAR(500),
    status            VARCHAR(40) NOT NULL,
    last_error        VARCHAR(1000),
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE invoice_counters (
    fiscal_year  VARCHAR(10) PRIMARY KEY,
    last_no      INT NOT NULL
);

CREATE TABLE invoices (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT NOT NULL REFERENCES orders (id),
    invoice_no   VARCHAR(40) NOT NULL UNIQUE,
    type         VARCHAR(20) NOT NULL,
    storage_key  VARCHAR(300) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE notification_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT,
    channel     VARCHAR(10) NOT NULL,
    recipient   VARCHAR(200) NOT NULL,
    subject     VARCHAR(300),
    status      VARCHAR(20) NOT NULL,
    error       VARCHAR(1000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
